def export_tailwind(tokens):
    typ = tokens.get("typography", {})
    leading = line_heights(tokens)
    obj = {
        "colors": dict(tokens.get("color", {})),
        "borderRadius": {k: f"{v}px" for k, v in tokens.get("radius", {}).items()},
        "spacing": {k: f"{v}px" for k, v in tokens.get("spacing", {}).items()},
        "fontSize": {k: f"{v}px" for k, v in typ.get("scale", {}).items()},
        "fontFamily": {role: split_families(font_stack(tokens, role)) for role in ("heading", "body", "mono")},
        "fontWeight": {k: str(v) for k, v in weights(typ).items()},
    }
    if leading:
        obj["lineHeight"] = {("DEFAULT" if k == "base" else kebab(k)): str(v) for k, v in leading.items()}
    if typ.get("letter_spacing"):
        obj["letterSpacing"] = {kebab(k): str(v) for k, v in typ["letter_spacing"].items()}
    if (tokens.get("layout", {}) or {}).get("max_width"):
        obj["maxWidth"] = {"container": f"{tokens['layout']['max_width']}px"}
    body = json.dumps(obj, indent=2, ensure_ascii=False)
    return "// Generated by style-compass — 粘进 tailwind.config.js 的 theme.extend。\nmodule.exports = " + body + ";\n"


