def export_css(tokens):
    typ = tokens.get("typography", {})
    lines = ["/* Generated by style-compass export_tokens.py — 改 tokens.json 后重跑。 */", ":root {"]
    for key, val in tokens.get("color", {}).items():
        lines.append(f"  --color-{kebab(key)}: {val};")
    if "on_accent" not in tokens.get("color", {}) and tokens.get("color", {}).get("accent"):
        lines.append(f"  --color-on-accent: {on_accent(tokens)};")
    for key, val in tokens.get("radius", {}).items():
        lines.append(f"  --radius-{kebab(key)}: {val}px;")
    for key, val in tokens.get("spacing", {}).items():
        lines.append(f"  --space-{kebab(key)}: {val}px;")
    if typ.get("cjk_sans"):
        lines.append(f"  --font-cjk-sans: {typ['cjk_sans']};")
    if typ.get("cjk_serif"):
        lines.append(f"  --font-cjk-serif: {typ['cjk_serif']};")
    for role in ("heading", "body", "mono"):
        if typ.get(f"{role}_font") or typ.get(f"latin_{role}") or typ.get("cjk_sans"):
            lines.append(f"  --font-{role}: {font_stack(tokens, role)};")
    for key, val in weights(typ).items():
        lines.append(f"  --weight-{key}: {val};")
    for key, val in typ.get("scale", {}).items():
        lines.append(f"  --text-{kebab(key)}: {val}px;")
    for key, val in line_heights(tokens).items():
        lines.append(f"  --leading-{kebab(key)}: {val};" if key != "base" else f"  --leading: {val};")
    for key, val in (typ.get("letter_spacing", {}) or {}).items():
        lines.append(f"  --tracking-{kebab(key)}: {val};")
    measure = (typ.get("measure", {}) or {}).get("cjk_max_em")
    if measure:
        lines.append(f"  --measure-cjk: {measure}em;")
    motion = tokens.get("motion", {})
    for key in ("duration_fast", "duration_base", "duration_slow"):
        if key in motion:
            lines.append(f"  --{kebab(key)}: {motion[key]}ms;")
    if motion.get("easing"):
        lines.append(f"  --easing: {motion['easing']};")
    for key, val in (tokens.get("elevation", {}) or {}).items():
        lines.append(f"  --shadow-{kebab(key)}: {val};")
    layout = tokens.get("layout", {}) or {}
    if layout.get("max_width"):
        lines.append(f"  --container-max: {layout['max_width']}px;")
    icon = tokens.get("icon", {}) or {}
    for key, val in (icon.get("sizes", {}) or {}).items():
        lines.append(f"  --icon-{kebab(key)}: {val}px;")
    if icon.get("stroke"):
        lines.append(f"  --icon-stroke: {icon['stroke']};")
    lines += ["}", ""]

    leading = line_heights(tokens)
    if is_cjk(tokens):
        body = "--leading-body" if "body" in leading else ("--leading" if "base" in leading else None)
        heading = "--leading-heading" if "heading" in leading else None
        lines += [
            "/* 中文排版底线。浏览器默认关闭 text-autospace，要显式打开；汉字不加负字距。 */",
            "html:lang(zh) { text-autospace: normal; }",
        ]
        rule = ["letter-spacing: 0;"]
        if body:
            rule.insert(0, f"line-height: var({body});")
        if measure:
            rule.append("max-inline-size: var(--measure-cjk);")
        lines.append(":lang(zh) :is(p, li, blockquote, dd) { " + " ".join(rule) + " }")
        heading_rule = "letter-spacing: 0;" + (f" line-height: var({heading});" if heading else "")
        lines.append(":lang(zh) :is(h1, h2, h3, h4, h5, h6) { " + heading_rule + " }")
        if (typ.get("letter_spacing", {}) or {}).get("latin_display"):
            lines.append(":lang(en) :is(h1, h2, .display) { letter-spacing: var(--tracking-latin-display); }")
    numerals = (typ.get("numerals", {}) or {}).get("data")
    if numerals:
        lines.append(f":is(td, .num, [data-numeric]) {{ font-variant-numeric: {numerals}; }}")
    lines += [
        "",
        "/* 减少动态：系统开启后，动画和过渡缩到几乎为零。 */",
        "@media (prefers-reduced-motion: reduce) {",
        "  *, *::before, *::after {",
        "    animation-duration: 0.01ms !important;",
        "    animation-iteration-count: 1 !important;",
        "    transition-duration: 0.01ms !important;",
        "    scroll-behavior: auto !important;",
        "  }",
        "}",
        "",
    ]
    return "\n".join(lines)


