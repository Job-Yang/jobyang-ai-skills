def export_swift(tokens):
    typ = tokens.get("typography", {})
    lines = [
        "// Generated by style-compass export_tokens.py — 不要手改，改 tokens.json 后重跑。",
        "import SwiftUI",
        "",
        "enum DesignTokens {",
        "    enum Palette {",
    ]
    for key, val in tokens.get("color", {}).items():
        try:
            r, g, b = hex_to_rgb01(val)
        except ValueError:
            continue
        lines.append(f"        static let {snake_to_camel(key)} = Color(red: {r}, green: {g}, blue: {b}) // {val}")
    lines += ["    }", "", "    enum Radius {"]
    for key, val in tokens.get("radius", {}).items():
        lines.append(f"        static let {snake_to_camel(key)}: CGFloat = {val}")
    lines += ["    }", "", "    enum Spacing {"]
    for key, val in tokens.get("spacing", {}).items():
        safe = snake_to_camel("s_" + key) if key[0].isdigit() else snake_to_camel(key)
        lines.append(f"        static let {safe}: CGFloat = {val}")
    lines += ["    }", "", "    enum FontSize {"]
    for key, val in typ.get("scale", {}).items():
        safe = snake_to_camel("s_" + key) if key[0].isdigit() else snake_to_camel(key)
        lines.append(f"        static let {safe}: CGFloat = {val}")
    lines.append("    }")
    leading = line_heights(tokens)
    if leading:
        lines += ["", "    /// CSS 行高倍数。SwiftUI 的 .lineSpacing() 是在字体自带行高上追加，需按字体校准后换算。",
                  "    enum LineHeight {"]
        for key, val in leading.items():
            lines.append(f"        static let {snake_to_camel(key)}: CGFloat = {val}")
        lines.append("    }")
    families = {role: first_named_family(split_families(font_stack(tokens, role))) for role in ("heading", "body", "mono")}
    if any(families.values()):
        lines += ["", "    /// 拉丁字体名，用于 Font.custom。中文字形由系统回退到苹方，不需要单独指定。", "    enum FontFamily {"]
        for role, name in families.items():
            if name:
                lines.append(f'        static let {role} = "{name}"')
        lines.append("    }")
    motion = tokens.get("motion", {})
    durations = {k: v for k, v in motion.items() if k.startswith("duration") and isinstance(v, (int, float))}
    if durations:
        lines += ["", "    enum Motion {"]
        for key, val in durations.items():
            lines.append(f"        static let {snake_to_camel(key)}: Double = {val / 1000:g}")
        lines.append("    }")
    lines += ["}", ""]
    return "\n".join(lines)


