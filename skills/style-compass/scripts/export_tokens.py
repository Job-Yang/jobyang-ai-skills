def read_brief(path):
    if not path:
        return ""
    with open(path, "r", encoding="utf-8") as f:
        text = f.read().strip()
    return re.sub(r"^# .*\n+", "", text, count=1)


def export_prompt(tokens, brief=""):
    """给后续写 UI 的模型读。只写本方向的约束，不写全局禁令：禁什么由方向决定。"""
    meta = tokens.get("meta", {})
    c = tokens.get("color", {})
    typ = tokens.get("typography", {})
    g = tokens.get("guardrails", {})
    name = meta.get("name", "自定义风格")
    leading = line_heights(tokens)
    out = [
        f"# 风格提示词 · {name}",
        "",
        "> 由 style-compass 生成。写本工程任何 UI 之前，先读这份、DESIGN.md 和 tokens.json；写完运行 lint_design.py check。",
        "> tokens.json 管一致性，下面的方向说明管气质。两者冲突时先停下来问，不要自己挑一个。",
        "",
        "## 这套界面要让人感到什么",
    ]
    if brief:
        out.append(brief)
    elif meta.get("summary"):
        out.append(meta["summary"])
    else:
        out.append("（没有方向简报。先补 design/direction.md，再重新导出。）")
    if meta.get("reference"):
        out += ["", "## 参考关系", f"参考 {meta['reference']}：只借它的{meta.get('borrow', '信息组织和节奏')}，不借它的颜色、字体和标志性构图。"]
    out += ["", "## 必须遵守", "- 颜色、圆角、间距、阴影、动效全部取 tokens.css 的变量，不写死 hex。"]
    out.append(f"- 字体：标题 `{font_stack(tokens, 'heading')}`；正文 `{font_stack(tokens, 'body')}`。")
    w = weights(typ)
    out.append(f"- 字重只用 {w['regular']} / {w['medium']} / {w['bold']}。")
    if is_cjk(tokens):
        body_lh = leading.get("body", leading.get("base", 1.75))
        out += [
            f"- 中文：`<html lang=\"{tokens.get('locale', {}).get('lang', 'zh-CN')}\">`；正文行高 {body_lh}；汉字不加负字距；中英文之间不手打空格，交给 text-autospace。",
            "- 数字列、金额、统计值用 tabular-nums 并右对齐。",
        ]
    out.append(f"- 主色 `{c.get('accent', '')}` 只用在主操作和当前状态上；背景 `{c.get('bg', '')}`，表面 `{c.get('surface', '')}`。")
    out.append("- 每个异步操作都有加载、失败和重试；危险操作优先给撤销，其次才是确认框，确认按钮写动作本身。")
    out.append("- 提供 prefers-reduced-motion 替代；可点击元素用 button 或 a，图标按钮写 aria-label。")
    use, avoid, watch = as_list(g.get("use")), as_list(g.get("avoid")), as_list(g.get("watch"))
    if use:
        out += ["", "## 这个方向要做的"] + [f"- {x}" for x in use]
    if avoid:
        out += ["", "## 这个方向要避开的"] + [f"- {x}" for x in avoid]
    if watch:
        out += ["", "## 这个方向容易掉进的默认长相", "写完自查；真要用，就把规则 ID 和理由写进 guardrails.accepted_defaults。"]
        out += [f"- {x}" for x in watch]
    out += ["", "## 表现力花在哪", g.get("moments") or "只在一两个关键时刻用强表达（比如首次完成、关键数据变化），其余保持安静。"]
    out += ["", "## 落地时",
            "- Web：引入 tokens.css，用 `var(--color-*)`、`var(--radius-*)` 等变量。",
            "- iOS：引入 DesignTokens.swift，用 `DesignTokens.Palette.*` 等常量。", ""]
    return "\n".join(out)


